interface LanguageContextValue {
  lang: Lang;
  setLang: (l: Lang, options?: { explicit?: boolean }) => void;
  t: (key: string, vars?: Record<string, string>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function format(template: string, vars?: Record<string, string>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}

const SUPPORTED: Lang[] = ["en", "pt", "pt-BR", "es", "fr", "hi"];

export function LanguageProvider({ children }: { children: ReactNode }) {
  // English is the universal default. Only honor an explicit non-English pick
  // made via the in-app switcher (tracked with `bateu_lang_explicit`). Legacy
  // PT defaults from previous releases are reset to English automatically.
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === "undefined") return "pt";
    const explicit = localStorage.getItem("bateu_lang_explicit") === "1";
    const stored = localStorage.getItem("bateu_lang") as Lang | null;
    if (explicit && stored && SUPPORTED.includes(stored)) return stored;
    return resolveLangFromCountry(getStoredCountry());
  });

  useEffect(() => {
    localStorage.setItem("bateu_lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang, options?: { explicit?: boolean }) => {
    if (!SUPPORTED.includes(l)) return;
    setLangState(l);
    if (typeof window !== "undefined" && options?.explicit !== false) {
      localStorage.setItem("bateu_lang_explicit", "1");
    }
  };

  const t = (key: string, vars?: Record<string, string>) => {
    // For PT/PT-BR: selected → pt → en → raw key
    // For other langs (hi, es, fr): selected → en → raw key (skip PT)
    const en = translations.en!;
    const dict = translations[lang] ?? en;
    const isPT = lang === "pt" || lang === "pt-BR";
    const pt = translations.pt!;
    const value = dict[key] ?? (isPT ? pt[key] : undefined) ?? en[key] ?? key;
    return format(value, vars);
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      lang: "pt" as Lang,
      setLang: () => {},
      t: (k: string, vars?: Record<string, string>) =>
        format(translations.pt?.[k] ?? translations.en?.[k] ?? k, vars),
    };
  }
  return ctx;
}

